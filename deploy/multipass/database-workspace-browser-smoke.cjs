// Requires an existing test site; does not reset the deployment VM.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const base = process.env.NAKPANEL_TEST_BASE_URL;
  const site = process.env.NAKPANEL_TEST_SITE_ID;
  assert(base && site, 'NAKPANEL_TEST_BASE_URL and NAKPANEL_TEST_SITE_ID are required');
  const browser = await chromium.launch({channel:'chrome',headless:true});
  try {
    const context = await browser.newContext({ignoreHTTPSErrors:true});
    const page = await context.newPage();
    await page.goto(base+'/login');
    await page.locator('[name=email]').fill(process.env.NAKPANEL_TEST_EMAIL || 'admin@nakpanel.test');
    await page.locator('[name=password]').fill(process.env.NAKPANEL_TEST_PASSWORD || 'NakpanelAdmin!2026');
    await page.locator('button[type=submit]').click();
    await page.waitForURL('**/dashboard');
    await page.goto(base+'/sites/'+site+'?tab=databases');
    await page.getByRole('button',{name:'Create database',exact:true}).click();
    const form=page.locator('dialog[open] form[data-np-domain-db-form]');
    const name='npws'+Date.now();
    await form.locator('[name=db_name]').fill(name);
    await form.getByRole('button',{name:'Generate password'}).click();
    const secret=await form.locator('[name=password]').inputValue();
    assert(secret.length>=16);
    const pending=page.waitForResponse(r=>r.request().method()==='POST' && new URL(r.url()).pathname==='/databases');
    await form.getByRole('button',{name:'Create database',exact:true}).click();
    const response=await pending;
    assert.equal(response.status(),202);
    const payload=await response.json();
    const id=payload.database_id;
    fs.writeFileSync(process.env.NAKPANEL_TEST_RESULT || '/tmp/nakpanel-database-smoke-result.json',JSON.stringify({id,name,site}),{mode:0o600});
    const row=page.locator('[data-np-db-id="'+id+'"]');
    await row.waitFor();
    await page.waitForFunction(id=>document.querySelector('[data-np-db-id="'+id+'"]')?.dataset.npDbState==='active',id,{timeout:90000});
    console.log('PASS creation automatically reached active; database ID '+id);
    const original=response.request();
    const replay=await context.request.post(base+'/databases',{data:original.postData(),headers:{'Content-Type':'application/x-www-form-urlencoded','X-Nakpanel-SPA':'true','X-Nakpanel-CSRF':original.headers()['x-nakpanel-csrf']}});
    assert.equal(replay.status(),202);assert.equal((await replay.json()).database_id,id);
    console.log('PASS duplicate submission returns same database');
    await row.getByRole('button',{name:'Connection details'}).click();
    await page.waitForFunction(name=>document.querySelector('[data-np-db-connection-output]').textContent.includes(name),name);
    assert(!(await page.locator('body').innerText()).includes(secret));
    await page.locator('dialog[open]').getByRole('button',{name:'Close',exact:true}).click();
    const manager=await Promise.all([context.waitForEvent('page'),row.getByRole('button',{name:'Open phpMyAdmin'}).click()]).then(v=>v[0]);
    await manager.waitForLoadState('networkidle');
    assert.match(await manager.locator('body').innerText(),new RegExp(name));
    assert(!(await manager.content()).includes(secret));
    console.log('PASS restricted phpMyAdmin signon without browser password');
    await require('./database-manager-browser-checks.cjs')(manager,context,name);
    await manager.close();
    const freshManager=await Promise.all([context.waitForEvent('page'),row.getByRole('button',{name:'Open phpMyAdmin'}).click()]).then(v=>v[0]);
    await freshManager.waitForLoadState('networkidle');
    const managerURL=freshManager.url();
    await row.getByRole('button',{name:'Reset password'}).click();
    const reset=page.locator('dialog[open] form[data-np-domain-db-form]');
    await reset.getByRole('button',{name:'Generate password'}).click();
    await reset.locator('[name=confirm]').check();
    const resetResponse=page.waitForResponse(r=>r.request().method()==='POST' && new URL(r.url()).pathname==='/databases/'+id+'/password');
    await reset.getByRole('button',{name:'Reset password',exact:true}).click();
    assert.equal((await resetResponse).status(),202);
    await page.waitForFunction(id=>document.querySelector('[data-np-db-id="'+id+'"] .np-domain-db-state small')?.textContent==='Ready to connect',id,{timeout:90000});
    const revoked=await context.request.get(managerURL);assert.equal(revoked.status(),404);
    console.log('PASS password rotation revoked prior manager session');
    await page.setViewportSize({width:390,height:844});
    await page.goto(base+'/sites/'+site+'?tab=databases');
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:'/tmp/nakpanel-database-mobile.png',fullPage:true,animations:'disabled'});
    console.log('PASS mobile layout; fixture metadata written for targeted cleanup');
  } finally {await browser.close();}
})().catch(error=>{console.error(error.message);process.exitCode=1;});
