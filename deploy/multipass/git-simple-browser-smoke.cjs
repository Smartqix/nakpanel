// Run only against an existing disposable Git test domain. Never deletes website files.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
 const base = process.env.NAKPANEL_TEST_BASE_URL;
 const site = process.env.NAKPANEL_TEST_SITE_ID;
 assert(base && site, 'Set panel URL and disposable site ID');
 const browser = await chromium.launch({channel:'chrome',headless:true});
 try {
  const context = await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  await page.addLocatorHandler(page.locator('#np-confirmation-dialog[open]'),async () => { await page.locator('[data-np-confirmation-accept]').click(); });
  page.on('dialog', dialog => dialog.accept());
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base+'/login');
  await page.locator('[name=email]').fill(process.env.NAKPANEL_TEST_EMAIL || 'admin@nakpanel.test');
  await page.locator('[name=password]').fill(process.env.NAKPANEL_TEST_PASSWORD || 'NakpanelAdmin!2026');
  await page.locator('button[type=submit]').click();
  await page.waitForURL('**/dashboard');
  await page.goto(base+'/sites/'+site+'/git');
  assert.match(await page.locator('body').innerText(),/git-workspace-.*\.test/,'Use a disposable git-workspace domain');
  const status = async () => (await context.request.get(base+'/sites/'+site+'/git/status')).json();
  let before = await status();
  if (before.repository && before.repository.connection_status!=='disconnected') {
   assert.equal(before.repository.remote_url,'https://github.com/octocat/Hello-World.git','Unexpected repository on disposable domain');
   await page.locator('[data-git-tabs] a[href="#git-settings"]').click();
   await page.getByRole('button',{name:'Remove Repository',exact:true}).click();
   await page.getByRole('button',{name:'Add Repository',exact:true}).waitFor({timeout:150000});
   before = await status();
  }
  await page.getByRole('button',{name:'Add Repository',exact:true}).click();
  const form = page.locator('#git-connect form');
  await form.locator('[name=remote_url]').fill('git@github.com:octocat/Hello-World.git');
  await form.locator('[name=remote_url]').press('Tab');
  await page.waitForFunction(() => document.querySelector('#git-connect [data-git-prepared-key]')?.textContent.startsWith('ssh-ed25519'),null,{timeout:30000});
  assert(await page.locator('#git-connect').evaluate(el=>el.open));
  const key = await form.locator('[data-git-prepared-key]').innerText();
  assert.match(await form.locator('[data-git-prepared-title]').innerText(),/Hello-World/);
  assert.equal((await status()).repository?.operation_revision,before.repository?.operation_revision,'Preparing a key saved repository intent');
  assert.equal((await status()).repository?.connection_status,before.repository?.connection_status);
  const repeated = await form.evaluate(async form => {
   const result = await fetch(form.action+'/key',{method:'POST',headers:{'X-Nakpanel-SPA':'true'},body:new URLSearchParams(new FormData(form))});
   return result.json();
  });
  assert.equal(repeated.public_key,key,'Key changed on retry');
  await page.screenshot({path:'/tmp/nakpanel-git-add-desktop.png'});
  await form.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('np-modal-open')),false);
  console.log('PASS inline key generation, reuse, no repository mutation, cancel');
  await page.getByRole('button',{name:'Add Repository',exact:true}).click();
  await form.locator('[name=remote_url]').fill('https://github.com/octocat/Hello-World.git');
  await form.locator('details').filter({has:page.locator('[name=branch]')}).locator('summary').click();
  await form.locator('[name=branch]').fill('nakpanel-nonexistent-test-branch');
  await form.getByRole('button',{name:'Add Repository',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#git-connect [data-git-message]')?.textContent.includes('Branch not found'),null,{timeout:150000});
  assert(await page.locator('#git-connect').evaluate(el=>el.open));
  assert.equal(await form.locator('[name=remote_url]').inputValue(),'https://github.com/octocat/Hello-World.git');
  console.log('PASS failed connection preserves dialog and form values');
  await form.locator('[name=branch]').fill('master');
  await form.getByRole('button',{name:'Add Repository',exact:true}).click();
  await page.getByRole('button',{name:'Pull updates',exact:true}).waitFor({timeout:150000});
  const connected = await status();
  assert.equal(connected.repository.connection_status,'connected');
  assert(connected.repository.fetched_revision,'Add did not clone');
  assert.equal(await page.locator('dialog[open]').count(),0);
  assert.equal(await page.locator('[data-np-git] noscript input[required]').count(),0,'Fallback inputs block AJAX removal');
  assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('np-modal-open')),false);
  await page.screenshot({path:'/tmp/nakpanel-git-connected-desktop.png'});
  console.log('PASS Add connects and fetches, closes dialog without full navigation');
  await page.getByRole('button',{name:'Deploy',exact:true}).click();
  await page.waitForFunction(revision=>document.querySelector('[data-git-deployed]')?.textContent===revision,connected.repository.fetched_revision,{timeout:150000});
  const published = await status();
  assert.equal(published.repository.deployed_revision,connected.repository.fetched_revision);
  console.log('PASS Deploy checks destination automatically and publishes the fetched commit');
  await page.locator('[data-git-tabs] a[href="#git-settings"]').click();
  await page.getByRole('button',{name:'Remove Repository',exact:true}).click();
  await page.getByRole('button',{name:'Add Repository',exact:true}).waitFor({timeout:150000});
  assert.equal((await status()).repository.connection_status,'disconnected');
  assert.equal((await status()).repository.deployed_revision || '',published.repository.deployed_revision || '');
  console.log('PASS Remove waits for completion and returns to empty state');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Add Repository',exact:true}).click();
  await form.locator('[name=remote_url]').fill('git@github.com:octocat/Hello-World.git');
  await form.locator('[name=remote_url]').press('Tab');
  await page.waitForFunction(() => document.querySelector('#git-connect [data-git-prepared-key]')?.textContent.startsWith('ssh-ed25519'),null,{timeout:30000});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  assert(await page.locator('#git-connect').evaluate(el=>el.scrollWidth<=el.clientWidth));
  await page.screenshot({path:'/tmp/nakpanel-git-add-mobile.png'});
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('np-modal-open')),false);
  assert.equal(await page.evaluate(()=>document.activeElement?.textContent.trim()),'Add Repository');
  assert.deepEqual(errors,[]);
  console.log('PASS reconnect key, 390px layout, Escape and focus restoration');
 } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
